/** Draw upper-case text at (x, y) in the font's 5x7 cells, scaled by `scale`. */
export function drawText(canvas, text, x, y, color, scale = 2) {
  let cx = x;
  for (const ch of String(text).toUpperCase()) {
    const glyph = GLYPHS[ch] ?? GLYPHS[' '];
    for (let row = 0; row < 7; row += 1) {
      for (let col = 0; col < 5; col += 1) {
        if (glyph[row][col] === '#') {
          canvas.fillRect(cx + col * scale, y + row * scale, scale, scale, color);
        }
      }
    }
    cx += 6 * scale;
  }
  return cx - x;
}

/** Width of `text` in pixels at the given scale. */
export function textWidth(text, scale = 2) {
  return String(text).length * 6 * scale - scale;
}
