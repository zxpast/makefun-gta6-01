/** Width of `text` in pixels at `scale` (each glyph is 5 columns + 1 gap). */
export function textWidth(text, scale) {
  return text.length * 6 * scale - scale;
}

/**
 * Draw `text` on `canvas` at (x, y) in `color`, upper-cased; unknown
 * characters draw as blanks. The font is 5 by 7, scaled by `scale`.
 */
export function drawText(canvas, text, x, y, scale, color) {
  let cursor = x;
  for (const raw of String(text).toUpperCase()) {
    const glyph = GLYPHS[raw] ?? GLYPHS[' '];
    for (let row = 0; row < 7; row += 1) {
      for (let col = 0; col < 5; col += 1) {
        if (glyph[row][col] !== '1') continue;
        canvas.fillRect(cursor + col * scale, y + row * scale, scale, scale, color);
      }
    }
    cursor += 6 * scale;
  }
}
