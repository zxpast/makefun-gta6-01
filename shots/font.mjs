// Draw `str` at (x, y) in the RGBA buffer, each glyph scaled by `scale`.
// `color` is [r, g, b]. Unknown characters draw as a blank. A few
// characters the HUD uses map onto glyphs that exist (em dash to hyphen,
// the music note to a star).
export function drawText(data, width, height, str, x, y, scale, color) {
  const [r, g, b] = color;
  let cx = x;
  const mapped = str.replace(/—/g, '-').replace(/♪/g, '*').replace(/’/g, "'");
  for (const ch of mapped) {
    const glyph = GLYPHS[ch] || GLYPHS['?'];
    for (let row = 0; row < 7; row += 1) {
      const bits = glyph[row];
      for (let col = 0; col < 5; col += 1) {
        if ((bits >> (4 - col)) & 1) {
          for (let sy = 0; sy < scale; sy += 1) {
            for (let sx = 0; sx < scale; sx += 1) {
              const px = cx + col * scale + sx;
              const py = y + row * scale + sy;
              if (px >= 0 && py >= 0 && px < width && py < height) {
                const o = (py * width + px) * 4;
                data[o] = r; data[o + 1] = g; data[o + 2] = b; data[o + 3] = 255;
              }
            }
          }
        }
      }
    }
    cx += 6 * scale;
  }
}
